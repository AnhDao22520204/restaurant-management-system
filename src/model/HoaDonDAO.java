    private static int getMaxSoHDFromDatabase() {
        String query = "SELECT MAX(SoHD) AS MaxSoHD FROM HoaDon";
        ResultSet rs = DbOperations.getData(query);
        try {
            if (rs != null && rs.next()) {
                return rs.getInt("MaxSoHD");
            }
        } catch (SQLException e) {
            e.printStackTrace();
        } finally {
            try {
                if (rs != null) {
                    rs.close();
                }
            } catch (SQLException e) {
                e.printStackTrace();
            }
        }
        // Trả về 0 nếu không có mã hóa đơn nào trong cơ sở dữ liệu
        return 0;
    }

    public static int getAutoGeneratedSoHD() {
        // Lấy mã hóa đơn lớn nhất từ cơ sở dữ liệu
        int maxSoHD = getMaxSoHDFromDatabase();
        // Tăng mã hóa đơn lớn nhất lấy được lên một đơn vị và trả về
        return maxSoHD + 1;
    }

