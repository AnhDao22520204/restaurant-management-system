    private void jBThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBThemActionPerformed

        //kiểm tra nhập

        if(jTTenNL.getText().isEmpty()||jTSoLuong.getText().isEmpty()||jTTongGT.getText().isEmpty()||jTNhaCC.getText().isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Nhập đầy đủ thông tin");
            return;
        }
        
        NguyenLieu nguyenlieu=new NguyenLieu();
         try {
            int maNL =0;
        String tenNL = jTTenNL.getText();
        int soLuong = Integer.parseInt(jTSoLuong.getText());
        int tongGT = Integer.parseInt(jTTongGT.getText());
        String nhaCC = jTNhaCC.getText();

        nguyenlieu  = new NguyenLieu(maNL, tenNL, soLuong, tongGT, nhaCC);
 
        } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(null, "lỗi giá trị nhập "); 
    }


        int x= NguyenLieuDAO.insert(nguyenlieu);
        if(x>0)
        {

            JOptionPane.showMessageDialog(null, "Thêm thành công");
            DefaultTableModel dtm = (DefaultTableModel) jTTable.getModel();
            dtm.setRowCount(0); // Xóa hết các dòng hiện có trong bảng
            ArrayList<NguyenLieu> list = NguyenLieuDAO.selectALL();
            for (NguyenLieu  nguyen : list) {
                dtm.addRow(new Object[]{nguyen.getMANL(), nguyen.getTENNL(),nguyen.getSOLUONG(), nguyen.getTONGGT(),nguyen.getNHACUNGCAP()});
            }

        } else  JOptionPane.showMessageDialog(null, "Thêm thất bại/ không rỏ nguyên nhân");
    }//GEN-LAST:event_jBThemActionPerformed

